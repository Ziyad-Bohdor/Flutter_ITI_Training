class Employee {
  String name;
  int age;
  double salary;
  String phone;
  String email;
  String address;
  String department;
  String jobTitle;

  Employee({
    required this.name,
    required this.age,
    required this.salary,
    required this.phone,
    required this.email,
    required this.address,
    required this.department,
    required this.jobTitle,
  });
}